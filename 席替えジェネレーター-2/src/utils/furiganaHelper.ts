export const NAME_READING_DICT: Record<string, string> = Object.fromEntries(RAW_NAME_ENTRIES);

// Convert Katakana to Hiragana
export function katakanaToHiragana(src: string): string {
  return src.replace(/[\u30a1-\u30f6]/g, (match) => {
    const chr = match.charCodeAt(0) - 0x60;
    return String.fromCharCode(chr);
  });
}

// Generate automatic furigana suggestion based on a Japanese name
export function suggestFurigana(name: string): string {
  if (!name || !name.trim()) return '';

  const cleanName = name.trim();

  // If already Hiragana or Katakana only
  if (/^[\u3040-\u309F\u30A0-\u30FF\s]+$/.test(cleanName)) {
    return katakanaToHiragana(cleanName);
  }

  // Split by space if any (e.g. "山田 太郎" or "山田　太郎")
  const parts = cleanName.split(/[\s\u3000]+/);
  if (parts.length > 1) {
    return parts.map(p => suggestFurigana(p)).join(' ');
  }

  // Exact match from dictionary
  if (NAME_READING_DICT[cleanName]) {
    return NAME_READING_DICT[cleanName];
  }

  // Greedy prefix matching algorithm for compound kanji names
  let result = '';
  let remaining = cleanName;

  while (remaining.length > 0) {
    let matched = false;

    // Try longest substring first (up to 4 chars down to 1 char)
    for (let len = Math.min(remaining.length, 4); len >= 1; len--) {
      const sub = remaining.substring(0, len);
      if (NAME_READING_DICT[sub]) {
        result += NAME_READING_DICT[sub];
        remaining = remaining.substring(len);
        matched = true;
        break;
      }
    }

    if (!matched) {
      // If character is already hiragana or katakana, keep/convert it
      const char = remaining[0];
      if (/[\u3040-\u309F]/.test(char)) {
        result += char;
      } else if (/[\u30A0-\u30FF]/.test(char)) {
        result += katakanaToHiragana(char);
      } else {
        result += char; // Fallback to original character
      }
      remaining = remaining.substring(1);
    }
  }

  return result;
}
